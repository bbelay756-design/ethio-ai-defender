"""
Empirical Feature Parity Test Suite for Milestone ML-07.

Compares features generated by app/ml/ember_v2.py against the reference standard
(tests/ml/reference_ember.py, transcribing elastic/ember/features.py) across
authorized synthetic and benign PE binary fixtures.
"""

import sys
import unittest
from pathlib import Path
from typing import Dict, Any, Tuple

import numpy as np

from app.ml.ember_v2 import EMBERFeatureExtractor, EMBER_V2_TOTAL_DIM, EMBER_V2_FEATURE_GROUPS
from app.ml.ember_adapter import EmberDatasetAdapter
from tests.ml.reference_ember import ReferencePEFeatureExtractor
from tests.test_pe_analyzer import build_synthetic_pe


# Offsets for each feature group within the 2,381-dimensional vector
GROUP_OFFSETS = {
    "histogram": (0, 256),
    "byteentropy": (256, 512),
    "strings": (512, 616),
    "general": (616, 626),
    "header": (626, 688),
    "section": (688, 943),
    "imports": (943, 2223),
    "exports": (2223, 2351),
    "datadirectories": (2351, 2381),
}


def evaluate_parity_on_bytes(bytez: bytes) -> Dict[str, Any]:
    """Run paired feature extraction and compare results across all 9 groups."""
    ref_ext = ReferencePEFeatureExtractor()
    local_ext = EMBERFeatureExtractor(print_warning=False)

    v_ref = ref_ext.feature_vector(bytez)
    v_local = local_ext.feature_vector(bytez)

    total_diff = np.abs(v_ref - v_local)
    exact_matches = int(np.sum(total_diff == 0.0))
    close_matches = int(np.sum(total_diff <= 1e-5))
    max_error = float(np.max(total_diff))

    group_results = {}
    for group_name, (start, end) in GROUP_OFFSETS.items():
        sub_ref = v_ref[start:end]
        sub_local = v_local[start:end]
        sub_diff = np.abs(sub_ref - sub_local)
        dim = end - start
        exact_sub = int(np.sum(sub_diff == 0.0))
        close_sub = int(np.sum(sub_diff <= 1e-5))
        max_sub = float(np.max(sub_diff)) if dim > 0 else 0.0
        group_results[group_name] = {
            "dim": dim,
            "exact": exact_sub,
            "close": close_sub,
            "max_error": max_sub,
            "parity": exact_sub == dim,
        }

    return {
        "total_dim": int(len(v_ref)),
        "exact_matches": exact_matches,
        "close_matches": close_matches,
        "exact_pct": round(exact_matches / EMBER_V2_TOTAL_DIM * 100, 2),
        "max_error": max_error,
        "group_results": group_results,
    }


class TestFeatureParity(unittest.TestCase):
    """Test suite validating empirical feature extraction parity."""

    def test_synthetic_pe_x64_parity(self):
        """Verify feature parity on synthetic 64-bit GUI executable."""
        bytez = build_synthetic_pe(is_64bit=True, is_dll=False, is_driver=False)
        report = evaluate_parity_on_bytes(bytez)

        self.assertEqual(report["total_dim"], EMBER_V2_TOTAL_DIM)
        # All 9 groups must match close tolerance
        self.assertEqual(report["close_matches"], EMBER_V2_TOTAL_DIM)
        self.assertLess(report["max_error"], 1e-5)
        for gname, ginfo in report["group_results"].items():
            self.assertEqual(ginfo["close"], ginfo["dim"], f"Group {gname} failed close match: {ginfo}")

    def test_synthetic_pe_x86_parity(self):
        """Verify feature parity on synthetic 32-bit console executable."""
        bytez = build_synthetic_pe(is_64bit=False, is_dll=False, is_driver=False, subsystem=3)
        report = evaluate_parity_on_bytes(bytez)

        self.assertEqual(report["total_dim"], EMBER_V2_TOTAL_DIM)
        self.assertEqual(report["close_matches"], EMBER_V2_TOTAL_DIM)
        self.assertLess(report["max_error"], 1e-5)

    def test_synthetic_dll_parity(self):
        """Verify feature parity on synthetic DLL binary."""
        bytez = build_synthetic_pe(is_64bit=True, is_dll=True, is_driver=False)
        report = evaluate_parity_on_bytes(bytez)

        self.assertEqual(report["total_dim"], EMBER_V2_TOTAL_DIM)
        self.assertEqual(report["close_matches"], EMBER_V2_TOTAL_DIM)
        self.assertLess(report["max_error"], 1e-5)

    def test_synthetic_driver_parity(self):
        """Verify feature parity on synthetic SYS driver binary."""
        bytez = build_synthetic_pe(is_64bit=True, is_dll=False, is_driver=True)
        report = evaluate_parity_on_bytes(bytez)

        self.assertEqual(report["total_dim"], EMBER_V2_TOTAL_DIM)
        self.assertEqual(report["close_matches"], EMBER_V2_TOTAL_DIM)
        self.assertLess(report["max_error"], 1e-5)

    def test_real_benign_binary_parity(self):
        """Verify feature parity on authorized real Windows PE executable."""
        exe_path = Path(sys.executable)
        self.assertTrue(exe_path.exists())
        bytez = exe_path.read_bytes()

        report = evaluate_parity_on_bytes(bytez)
        self.assertEqual(report["total_dim"], EMBER_V2_TOTAL_DIM)
        # Verify close matches across real executable
        self.assertEqual(report["close_matches"], EMBER_V2_TOTAL_DIM)
        self.assertLess(report["max_error"], 1e-5)

    def test_three_way_parity_synthetic_pe(self):
        """Verify 3-way exact parity between raw-PE extractor, reference extractor, and dataset adapter."""
        bytez = build_synthetic_pe(is_64bit=True, is_dll=False, is_driver=False)
        ref_ext = ReferencePEFeatureExtractor()
        local_ext = EMBERFeatureExtractor(print_warning=False)
        adapter = EmberDatasetAdapter()

        v_ref = ref_ext.feature_vector(bytez)
        v_local = local_ext.feature_vector(bytez)
        raw_dict = ref_ext.raw_features(bytez)
        raw_dict["sha256"] = "0" * 64
        raw_dict["appeared"] = "2018-01"
        raw_dict["label"] = 0
        v_adapter, _ = adapter.parse_record(raw_dict)

        np.testing.assert_allclose(v_local, v_ref, atol=1e-5)
        np.testing.assert_allclose(v_adapter, v_ref, atol=1e-5)
        np.testing.assert_allclose(v_local, v_adapter, atol=1e-5)

    def test_three_way_parity_real_binary(self):
        """Verify 3-way exact parity on a real host PE executable (python.exe)."""
        bytez = Path(sys.executable).read_bytes()
        ref_ext = ReferencePEFeatureExtractor()
        local_ext = EMBERFeatureExtractor(print_warning=False)
        adapter = EmberDatasetAdapter()

        v_ref = ref_ext.feature_vector(bytez)
        v_local = local_ext.feature_vector(bytez)
        raw_dict = ref_ext.raw_features(bytez)
        raw_dict["sha256"] = "0" * 64
        raw_dict["appeared"] = "2018-01"
        raw_dict["label"] = 0
        v_adapter, _ = adapter.parse_record(raw_dict)

        np.testing.assert_allclose(v_local, v_ref, atol=1e-5)
        np.testing.assert_allclose(v_adapter, v_ref, atol=1e-5)
        np.testing.assert_allclose(v_local, v_adapter, atol=1e-5)

    def test_malformed_inputs_produce_finite_vectors_and_safe_rejections(self):
        """Verify that malformed and non-PE inputs produce finite vectors without exceptions."""
        local_ext = EMBERFeatureExtractor(print_warning=False)
        malformed_inputs = [
            b"",
            b"MZ",
            b"MZ\x00\x01\x02\x03",
            b"\x42" * 1024,
            b"MZ" + b"\x00" * 58 + b"\x80\x00\x00\x00" + b"\x00" * 64 + b"PE\x00\x00",
        ]
        for bad_input in malformed_inputs:
            vec = local_ext.feature_vector(bad_input)
            self.assertEqual(vec.shape, (EMBER_V2_TOTAL_DIM,))
            self.assertEqual(vec.dtype, np.float32)
            self.assertTrue(np.all(np.isfinite(vec)))


if __name__ == "__main__":
    unittest.main()
